create policy updates_read on public.project_updates for select to authenticated using(public.lws_is_staff() or (customer_user_id=auth.uid() and is_visible_to_customer=true));
create policy updates_write on public.project_updates for all to authenticated using(public.lws_is_staff()) with check(public.lws_is_staff());

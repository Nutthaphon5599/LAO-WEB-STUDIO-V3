create policy leads_staff on public.leads for all to authenticated using(public.lws_is_staff()) with check(public.lws_is_staff());
create policy appointments_staff on public.appointments for all to authenticated using(public.lws_is_staff()) with check(public.lws_is_staff());
create policy quotations_staff on public.quotations for all to authenticated using(public.lws_is_staff()) with check(public.lws_is_staff());
create policy tasks_read on public.tasks for select to authenticated using(public.lws_is_staff() or customer_user_id=auth.uid());
create policy tasks_write on public.tasks for all to authenticated using(public.lws_is_staff()) with check(public.lws_is_staff());
